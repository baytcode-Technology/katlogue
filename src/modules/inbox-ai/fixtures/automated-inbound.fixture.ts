/**
 * Automated inbound text must not call the model.
 * Run: npx tsx src/modules/inbox-ai/fixtures/automated-inbound.fixture.ts
 */
import assert from 'node:assert/strict'
import { shouldSkipAutomatedInbound } from '../services/skip-automated-inbound.js'

let failed = 0

function test(name: string, fn: () => void): void {
  try {
    fn()
    console.log(`  ok ${name}`)
  } catch (err) {
    failed += 1
    console.error(`  FAIL ${name}:`, err instanceof Error ? err.message : err)
  }
}

console.log('\n=== Automated inbound ===')

test('shop welcome with department names is skipped', () => {
  const text =
    'Hello! Welcome to Shrox. You can explore our Men department with Shirts and Pants at https://eatomatic.co.in. What would you like to see today?'
  assert.equal(shouldSkipAutomatedInbound(text), true)
})

test('channel welcome and thank-you posts are skipped', () => {
  assert.equal(
    shouldSkipAutomatedInbound("Welcome to RBI's Official WhatsApp Channel"),
    true
  )
  assert.equal(shouldSkipAutomatedInbound('Thank you for connecting with the Reserve Bank of India'), true)
})

test('AI disclosure is skipped', () => {
  assert.equal(
    shouldSkipAutomatedInbound(
      "You're chatting with yourstore. Some replies may be generated by AI."
    ),
    true
  )
})

test('first Hai with no store greeting is not skipped', () => {
  assert.equal(shouldSkipAutomatedInbound('Hai', []), false)
})

test('Hai after a store welcome is skipped', () => {
  assert.equal(
    shouldSkipAutomatedInbound('Hai', [
      { role: 'store', text: 'Hi, welcome. Browse our catalog.\nhttps://shrox.aishopy.io' },
    ]),
    true
  )
})

test('a real shirt question is not skipped', () => {
  assert.equal(shouldSkipAutomatedInbound('do you have shirts'), false)
})

if (failed > 0) {
  console.error(`\n${failed} automated inbound fixture(s) failed`)
  process.exit(1)
}
console.log('\nAll automated inbound fixtures passed.')
