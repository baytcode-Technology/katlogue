import type { ConversationHistoryLine } from './parse-customer-intent.service.js'

const DISCLOSURE_PATTERN =
  /some replies may be generated by ai|you're chatting with/i

const CHANNEL_PATTERN = /official whatsapp channel|thank you for connecting/i

const SHOP_WELCOME_PHRASE =
  /welcome to|our store link|what would you like to see or order|you can explore our|browse our catalog/i

const STORE_URL_PATTERN = /https?:\/\/|\baishopy\.io\b/i

const STORE_GREETING_PATTERN =
  /welcome|browse our catalog|swagatham|സ്വാഗതം|catalog ithu|our store link|what would you like to see or order|you can explore our/i

const BARE_HELLO_PATTERN = /^(hi|hello|hey|hai|namaste|welcome)[\s!.?,]*$/i

const REAL_ASK_PATTERN = /\b(product|order|price|size|return|shirt|pant|buy)\b/i

function storeAlreadyGreeted(recentMessages: ConversationHistoryLine[]): boolean {
  return recentMessages.some(
    (line) => line.role === 'store' && STORE_GREETING_PATTERN.test(line.text)
  )
}

/** True when this inbound text is another bot, a channel post, or a second hello. */
export function shouldSkipAutomatedInbound(
  text: string,
  recentMessages: ConversationHistoryLine[] = []
): boolean {
  const trimmed = text.trim()
  if (!trimmed) return false
  if (DISCLOSURE_PATTERN.test(trimmed)) return true
  if (CHANNEL_PATTERN.test(trimmed)) return true
  if (SHOP_WELCOME_PHRASE.test(trimmed) && STORE_URL_PATTERN.test(trimmed)) return true
  if (
    BARE_HELLO_PATTERN.test(trimmed) &&
    !REAL_ASK_PATTERN.test(trimmed) &&
    storeAlreadyGreeted(recentMessages)
  ) {
    return true
  }
  return false
}
